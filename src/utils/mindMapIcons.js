const ICON_NAME_RE = /^[A-Z][A-Za-z0-9]{0,59}$/;

export function sanitizeMindMapIcon(value) {
  if (value == null) return '';
  const name = String(value).trim();
  if (!name) return '';
  if (!ICON_NAME_RE.test(name)) return '';
  return name;
}

export function sanitizeMindMapImageUrl(value) {
  if (value == null) return '';
  const raw = String(value).trim();
  if (!raw) return '';
  if (raw.startsWith('data:image/')) {
    if (raw.length > 900000) return '';
    if (!/^data:image\/(png|jpe?g|gif|webp|svg\+xml);base64,/i.test(raw.slice(0, 80))) return '';
    return raw;
  }
  if (/^https?:\/\//i.test(raw)) return raw.slice(0, 2000);
  if (raw.startsWith('/')) return raw.slice(0, 500);
  return '';
}



export function isLucideIconExportName(name) {
  return typeof name === 'string' && ICON_NAME_RE.test(name) && !name.endsWith('Icon') && !name.startsWith('Lucide') && name !== 'Icon';
}
